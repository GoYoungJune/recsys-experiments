"""Post-hoc robustness check for part 4 (NOT pre-registered): do U3/U4 depend on the luck of one split?

Repeats the train/test split with 50 seeds. For speed the model family is fixed to the one chosen in the
main run (logistic-regression T-learner) instead of re-running 5-fold selection per split.
Outputs: results/uplift/robustness.md, robustness.json

    python scripts/uplift_robustness.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from tabulate import tabulate

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from recsys.uplift.analysis import (  # noqa: E402
    CONTROL, MENS, WOMENS, TLearner, best_arm_policy, bootstrap_policy_values, budget_policy, features,
    load_hillstrom, policy_value, stratified_split, summarize_boot,
)

SEEDS = range(50)
N_BOOT = 2_000
OUT = ROOT / "results" / "uplift"


def make():
    return make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000))


def main() -> None:
    df = load_hillstrom(ROOT / "data" / "hillstrom" / "hillstrom.csv")
    X, arm, y = features(df), df["arm"].to_numpy(), df["visit"].to_numpy(dtype=float)
    rows = []
    for seed in SEEDS:
        tr, te = stratified_split(arm, seed=seed)
        up = TLearner(make).fit(X[tr], arm[tr], y[tr]).predict_uplift(X[te])
        single = MENS if y[tr][arm[tr] == MENS].mean() >= y[tr][arm[tr] == WOMENS].mean() else WOMENS
        pols = {"model": best_arm_policy(up), "single": np.full(len(te), single),
                "top50": budget_policy(up, 0.5), "control": np.full(len(te), CONTROL)}
        yt, at = y[te], arm[te]
        v = {k: policy_value(yt, at, p) for k, p in pols.items()}
        b = bootstrap_policy_values(yt, at, pols, n_boot=N_BOOT, seed=seed)
        u3 = summarize_boot(b["model"] - b["single"])
        u4 = summarize_boot((b["top50"] - b["control"]) / (b["single"] - b["control"]), null=0.5)
        rows.append({"seed": seed, "single": "Mens" if single == MENS else "Womens",
                     "u3_diff": v["model"] - v["single"], "u3_ci_low": u3["ci_low"], "u3_ci_high": u3["ci_high"],
                     "u4_ratio": (v["top50"] - v["control"]) / (v["single"] - v["control"]),
                     "u4_ci_low": u4["ci_low"], "u4_ci_high": u4["ci_high"]})
        print(f"seed {seed:2d} U3 {rows[-1]['u3_diff']:+.4f} U4 {rows[-1]['u4_ratio']:.3f}", flush=True)

    d = np.array([r["u3_diff"] for r in rows])
    q = np.array([r["u4_ratio"] for r in rows])
    summary = {
        "n_splits": len(rows),
        "single_is_mens": sum(r["single"] == "Mens" for r in rows),
        "u3_median": float(np.median(d)), "u3_min": float(d.min()), "u3_max": float(d.max()),
        "u3_share_positive": float((d > 0).mean()),
        "u3_n_ci_above_0": sum(r["u3_ci_low"] > 0 for r in rows),
        "u3_n_ci_below_0": sum(r["u3_ci_high"] < 0 for r in rows),
        "u4_median": float(np.median(q)), "u4_min": float(q.min()), "u4_max": float(q.max()),
        "u4_n_ci_above_half": sum(r["u4_ci_low"] > 0.5 for r in rows),
    }
    (OUT / "robustness.json").write_text(json.dumps({"summary": summary, "splits": rows}, indent=2), encoding="utf-8")
    s = summary
    L = ["# Robustness of U3/U4 across 50 train/test splits (post-hoc, NOT pre-registered)", "",
         "Auto-generated by `scripts/uplift_robustness.py`. Logistic-regression T-learner fixed (the model chosen in "
         f"the main run); bootstrap {N_BOOT:,} per split.", "",
         tabulate([
             ["single best e-mail on train is Mens", f"{s['single_is_mens']} / {s['n_splits']} splits"],
             ["U3 model - single: median [min, max]", f"{s['u3_median']:+.4f} [{s['u3_min']:+.4f}, {s['u3_max']:+.4f}]"],
             ["U3 share of splits with diff > 0", f"{s['u3_share_positive']:.0%}"],
             ["U3 splits with 95% CI above 0 / below 0", f"{s['u3_n_ci_above_0']} / {s['u3_n_ci_below_0']}"],
             ["U4 ratio: median [min, max]", f"{s['u4_median']:.3f} [{s['u4_min']:.3f}, {s['u4_max']:.3f}]"],
             ["U4 splits with 95% CI above 0.5", f"{s['u4_n_ci_above_half']} / {s['n_splits']}"],
         ], headers=["quantity", "value"], tablefmt="github", disable_numparse=True), ""]
    (OUT / "robustness.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
