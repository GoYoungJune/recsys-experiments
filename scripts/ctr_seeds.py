"""Post-hoc check for part 5 (NOT pre-registered): are the C1/C2 model gaps larger than training-seed noise?

Retrains LR, FM and DeepFM with 5 seeds on the same temporal split and reports test AUC per seed.
Outputs: results/ctr/seeds.md, seeds.json

    python scripts/ctr_seeds.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import torch
from tabulate import tabulate

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from recsys.ctr.data import SINGLE_FIELDS, Encoder, load_ml1m, temporal_split  # noqa: E402
from recsys.ctr.metrics import auc, ece  # noqa: E402
from recsys.ctr.models import CTRModel, fit, predict  # noqa: E402

SEEDS = [0, 1, 2, 3, 4]
KINDS = {"lr": "LR", "fm": "FM", "deepfm": "DeepFM"}
OUT = ROOT / "results" / "ctr"
torch.set_num_threads(8)


def main() -> None:
    parts = temporal_split(load_ml1m(ROOT / "data" / "ml-1m"))
    enc = Encoder(SINGLE_FIELDS).fit(parts["train"])
    tr, va, te = (enc.transform(parts[k]) for k in ("train", "valid", "test"))
    y = te.label.astype(float)
    res = {k: {"auc": [], "ece": [], "best_epoch": []} for k in KINDS}
    for seed in SEEDS:
        for kind in KINDS:
            m = CTRModel(kind, enc.field_sizes, enc.n_genres, dim=16, seed=seed)
            info = fit(m, tr, va, seed=seed, log=lambda *_: None)
            p = predict(m, te)
            res[kind]["auc"].append(auc(y, p))
            res[kind]["ece"].append(ece(y, p))
            res[kind]["best_epoch"].append(info["best_epoch"])
            print(f"seed {seed} {KINDS[kind]:6s} AUC {res[kind]['auc'][-1]:.4f} ECE {res[kind]['ece'][-1]:.4f} "
                  f"best epoch {info['best_epoch']}", flush=True)
    fm_lr = np.array(res["fm"]["auc"]) - np.array(res["lr"]["auc"])
    dfm_fm = np.array(res["deepfm"]["auc"]) - np.array(res["fm"]["auc"])
    summary = {k: {"auc_mean": float(np.mean(v["auc"])), "auc_sd": float(np.std(v["auc"], ddof=1)),
                   "auc_min": float(np.min(v["auc"])), "auc_max": float(np.max(v["auc"])),
                   "ece_mean": float(np.mean(v["ece"])), "best_epochs": v["best_epoch"]} for k, v in res.items()}
    summary["fm_minus_lr"] = {"mean": float(fm_lr.mean()), "min": float(fm_lr.min()), "max": float(fm_lr.max()),
                              "n_positive": int((fm_lr > 0).sum())}
    summary["deepfm_minus_fm"] = {"mean": float(dfm_fm.mean()), "min": float(dfm_fm.min()), "max": float(dfm_fm.max()),
                                  "n_positive": int((dfm_fm > 0).sum())}
    (OUT / "seeds.json").write_text(json.dumps({"seeds": SEEDS, "per_seed": res, "summary": summary}, indent=2),
                                    encoding="utf-8")
    rows = [[KINDS[k], f"{s['auc_mean']:.4f}", f"{s['auc_sd']:.4f}", f"[{s['auc_min']:.4f}, {s['auc_max']:.4f}]",
             f"{s['ece_mean']:.4f}", ", ".join(map(str, s["best_epochs"]))] for k, s in summary.items() if k in KINDS]
    a, b = summary["fm_minus_lr"], summary["deepfm_minus_fm"]
    L = ["# Training-seed robustness for part 5 (post-hoc, NOT pre-registered)", "",
         f"Auto-generated by `scripts/ctr_seeds.py`. Seeds {SEEDS}; same split, features and fixed hyper-parameters.", "",
         tabulate(rows, headers=["model", "test AUC mean", "SD over seeds", "[min, max]", "ECE mean", "best epochs"],
                  tablefmt="github", disable_numparse=True), "",
         tabulate([["FM - LR", f"{a['mean']:+.4f}", f"[{a['min']:+.4f}, {a['max']:+.4f}]", f"{a['n_positive']} / {len(SEEDS)}"],
                   ["DeepFM - FM", f"{b['mean']:+.4f}", f"[{b['min']:+.4f}, {b['max']:+.4f}]", f"{b['n_positive']} / {len(SEEDS)}"]],
                  headers=["same-seed AUC difference", "mean", "[min, max]", "seeds with diff > 0"],
                  tablefmt="github", disable_numparse=True), ""]
    (OUT / "seeds.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
